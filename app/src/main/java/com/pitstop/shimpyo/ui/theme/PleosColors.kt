    val textTertiary: Color,
    val textQuaternary: Color,
    val textOnFilled: Color,
    val iconPrimary: Color,
    val iconTertiary: Color,
    // buttons
    val buttonBasicEnabled: Color,
    val buttonBasicPressed: Color,
    val buttonBasicDisabled: Color,
    val buttonFilledEnabled: Color,
    val buttonFilledPressed: Color,
    val buttonFilledDisabled: Color,
    val buttonSwitchEnabled: Color,
    val buttonSwitchPressed: Color,
    val controllerTabBackground: Color,
    // dim / divider
    val dimPrimary: Color,
    val dimSecondary: Color,
    val dimTertiary: Color,
    // switch
    val switchOn: Color,
    val switchOff: Color,
    val switchKnobOn: Color,
    val switchKnobOff: Color,
    // climate
    val climateButtonEnabled: Color,
    val climateButtonSelected: Color,
    val climateBorder: Color,
    // informative
    val active: Color,
    val positive: Color,
    val negative: Color,
    // regulation
    val regulationGreen: Color,
    val regulationYellow: Color,
    val regulationOrange: Color,
    val regulationRed: Color,
    // Gleo(차량 AI 에이전트) 대화 표현
    val gleoSurface: Color,
    val gleoBubblePrimary: Color,
    val gleoBubbleSecondary: Color,
    val gleoBubbleTertiary: Color,
    val gleoSpeaker: Color,
    val overlay: Color,
)

